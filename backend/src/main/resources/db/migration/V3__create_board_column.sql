-- 列(ボードの列)を専用テーブルにし、task が参照する形に変更する。
-- 「column」は SQL の予約語のため、テーブル名は board_column とする。
CREATE TABLE board_column (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      VARCHAR(100) NOT NULL,
    position   INTEGER      NOT NULL DEFAULT 0,
    sort_mode  VARCHAR(20)  NOT NULL DEFAULT 'MANUAL'
);

-- 初期列(F-10)。
INSERT INTO board_column (title, position) VALUES
    ('未着手', 0),
    ('進行中', 1),
    ('完了',   2);

-- task: 固定の status をやめ、列への参照(column_id)に置き換える。
-- 列を削除すると、その列のカードも一緒に削除される(F-13)。
DROP INDEX idx_task_status_position;
ALTER TABLE task DROP COLUMN status;
ALTER TABLE task ADD COLUMN column_id BIGINT NOT NULL
    REFERENCES board_column (id) ON DELETE CASCADE;
CREATE INDEX idx_task_column_position ON task (column_id, position);
